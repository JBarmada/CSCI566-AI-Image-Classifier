import argparse
import base64
import csv
import os
import threading
import time
from concurrent.futures import ThreadPoolExecutor, as_completed
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
MODEL = "claude-opus-5-5"
FIELDS = ["blind_id", "raw_response", "timestamp_utc", "model", "stop_reason",
          "input_tokens", "output_tokens", "error"]

PROMPT = """
Analyze the provided image and estimate the probability that it was
generated by an AI system rather than captured by a real camera.

Return ONLY a JSON object in this format:
{"p_fake": 0}

p_fake must be a number from 0 to 100:
0 means certainly real; 100 means certainly AI-generated.

Do not assume that unusual visual characteristics necessarily
indicate AI generation.
"""


def done_ids(path: Path) -> set:
    if not path.exists():
        return set()
    with path.open(newline="", encoding="utf-8") as f:
        return {row["blind_id"] for row in csv.DictReader(f) if not row.get("error")}


def ask(client, model: str, image: Path, max_tokens: int) -> dict:
    data = base64.standard_b64encode(image.read_bytes()).decode()
    msg = client.messages.create(
        model=model,
        max_tokens=max_tokens,
        messages=[{"role": "user", "content": [
            {"type": "image", "source": {"type": "base64", "media_type": "image/png", "data": data}},
            {"type": "text", "text": PROMPT},
        ]}],
    )
    text = "".join(block.text for block in msg.content if getattr(block, "type", "") == "text").strip()
    return {"raw_response": text, "model": msg.model, "stop_reason": msg.stop_reason,
            "input_tokens": msg.usage.input_tokens, "output_tokens": msg.usage.output_tokens}


def run(client, blind_dir: Path, output: Path, model: str, workers: int, max_tokens: int,
        limit: int = 0, retries: int = 3) -> int:
    images = sorted(blind_dir.glob("img_*.png"))
    if not images:
        raise SystemExit(f"No img_*.png files in {blind_dir}")
    skip = done_ids(output)
    todo = [p for p in images if p.stem not in skip]
    if limit:
        todo = todo[:limit]
    print(f"{len(images)} images, {len(skip)} already done, running {len(todo)}")

    new_file = not output.exists()
    lock = threading.Lock()
    with output.open("a", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=FIELDS)
        if new_file:
            writer.writeheader()

        def one(image: Path) -> dict:
            last = ""
            for attempt in range(retries):
                try:
                    return {"blind_id": image.stem, **ask(client, model, image, max_tokens), "error": ""}
                except Exception as exc:
                    last = f"{type(exc).__name__}: {exc}"
                    time.sleep(2 ** attempt * 5)
            return {"blind_id": image.stem, "raw_response": "", "model": model, "stop_reason": "",
                    "input_tokens": "", "output_tokens": "", "error": last}

        failed = 0
        with ThreadPoolExecutor(max_workers=workers) as pool:
            futures = [pool.submit(one, image) for image in todo]
            for n, fut in enumerate(as_completed(futures), 1):
                row = fut.result()
                row["timestamp_utc"] = datetime.now(timezone.utc).isoformat()
                with lock:
                    writer.writerow(row)
                    f.flush()
                failed += bool(row["error"])
                if n % 25 == 0 or n == len(todo):
                    print(f"  {n}/{len(todo)} done, {failed} failed")
    return failed


def main(argv=None):
    parser = argparse.ArgumentParser(description="Rate each blind image with one isolated Claude API call.")
    parser.add_argument("--blind-dir", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=HERE / "claude_api_responses.csv")
    parser.add_argument("--model", default=MODEL)
    parser.add_argument("--workers", type=int, default=4)
    parser.add_argument("--max-tokens", type=int, default=4000)
    parser.add_argument("--limit", type=int, default=0, help="Only run this many images (for a test)")
    args = parser.parse_args(argv)

    if not os.environ.get("ANTHROPIC_API_KEY"):
        raise SystemExit("Set ANTHROPIC_API_KEY in this terminal first (see README).")
    import anthropic

    failed = run(anthropic.Anthropic(max_retries=3), args.blind_dir, args.output, args.model,
                 args.workers, args.max_tokens, args.limit)
    if failed:
        print(f"{failed} images failed; run the same command again to retry just those.")


if __name__ == "__main__":
    main()
