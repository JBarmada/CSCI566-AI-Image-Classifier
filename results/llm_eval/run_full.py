import os
import re
import json
import time
import base64
import argparse
import mimetypes
from pathlib import Path
from datetime import datetime, timezone

import pandas as pd
from google import genai
from google.genai import types
from groq import Groq

ROOT = Path("data/extracted/GenImage_Compact")
OUT = Path("results/llm_eval")
MANIFEST = OUT / "unique_api_manifest.csv"

MODELS = {
    "gemini": {
        "provider": "Google",
        "model": "gemini-3.1-flash-lite",
        "output": OUT / "gemini_full_predictions.csv",
    },
    "groq": {
        "provider": "Groq",
        "model": "qwen/qwen3.8-27b",
        "output": OUT / "groq_full_predictions.csv",
    },
}

PROMPT = """
Analyze the provided image and estimate the probability that it was
generated by an AI system rather than captured by a real camera.

Return ONLY a JSON object in this format:
{"p_fake": 0}

p_fake must be a number from 0 to 100:
0 means certainly real; 100 means certainly AI-generated.

Do not assume that unusual visual characteristics necessarily
indicate AI generation.
"""

def parse_probability(raw):
    """Extract and validate p_fake from a model response."""
    text = raw.strip()
    text = re.sub(r"^```(?:json)?\s*", "", text)
    text = re.sub(r"\s*```$", "", text)

    result = json.loads(text)
    value = float(result["p_fake"])

    if not 0 <= value <= 100:
        raise ValueError(f"p_fake outside 0-100: {value}")

    return value


def call_gemini(client, image_bytes, mime_type, model):
    response = client.models.generate_content(
        model=model,
        contents=[
            PROMPT,
            types.Part.from_bytes(
                data=image_bytes,
                mime_type=mime_type,
            ),
        ],
        config=types.GenerateContentConfig(
            temperature=0,
            max_output_tokens=128,
            response_mime_type="application/json",
        ),
    )
    return response.text


def call_groq(client, image_bytes, mime_type, model):
    encoded = base64.b64encode(image_bytes).decode("utf-8")
    data_url = f"data:{mime_type};base64,{encoded}"

    response = client.chat.completions.create(
        model=model,
        messages=[
            {
                "role": "user",
                "content": [
                    {"type": "text", "text": PROMPT},
                    {
                        "type": "image_url",
                        "image_url": {"url": data_url},
                    },
                ],
            }
        ],
        temperature=0,
        max_completion_tokens=128,
        response_format={"type": "json_object"},
    )
    return response.choices[0].message.content


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--model",
        choices=["gemini", "groq"],
        required=True,
    )
    parser.add_argument(
        "--limit",
        type=int,
        default=0,
        help="Optional maximum number of new images to process.",
    )
    parser.add_argument(
        "--delay",
        type=float,
        default=None,
        help="Seconds to wait between requests.",
    )
    args = parser.parse_args()

    config = MODELS[args.model]
    model = config["model"]
    output_file = config["output"]

    key_name = "GEMINI_API_KEY" if args.model == "gemini" else "GROQ_API_KEY"
    api_key = os.environ.get(key_name)

    if not api_key:
        raise RuntimeError(f"{key_name} is not set in this shell.")

    if args.model == "gemini":
        client = genai.Client(api_key=api_key)
    else:
        client = Groq(api_key=api_key)

    delay = args.delay
    if delay is None:
        delay = 2 if args.model == "gemini" else 25

    manifest = pd.read_csv(MANIFEST)

    if output_file.exists():
        previous = pd.read_csv(output_file)
        records = {
            str(row["sha256"]): row.to_dict()
            for _, row in previous.iterrows()
        }
    else:
        records = {}

    completed = {
        sha for sha, record in records.items()
        if record.get("status") == "success"
    }

    pending = manifest[
        ~manifest["sha256"].astype(str).isin(completed)
    ].copy()

    if args.limit:
        pending = pending.head(args.limit)

    print(f"Provider: {config['provider']}")
    print(f"Model: {model}")
    print(f"Images in manifest: {len(manifest)}")
    print(f"Already completed: {len(completed)}")
    print(f"Remaining this run: {len(pending)}")
    print(f"Delay between requests: {delay} seconds")
    print(f"Output: {output_file}")
    print("")

    for index, (_, row) in enumerate(pending.iterrows(), start=1):
        sha = str(row["sha256"])
        image_path = ROOT / str(row["path"])

        print(f"[{index}/{len(pending)}] {image_path.name}", flush=True)

        record = {
            "sha256": sha,
            "path": str(row["path"]),
            "model": model,
            "provider": config["provider"],
            "p_fake": None,
            "raw_response": None,
            "status": "error",
            "error": None,
            "timestamp_utc": None,
        }

        try:
            if not image_path.is_file():
                raise FileNotFoundError(str(image_path))

            image_bytes = image_path.read_bytes()
            mime_type = (
                mimetypes.guess_type(image_path.name)[0]
                or "image/jpeg"
            )

            raw = None
            last_error = None

            for attempt in range(5):
                try:
                    if args.model == "gemini":
                        raw = call_gemini(
                            client, image_bytes, mime_type, model
                        )
                    else:
                        raw = call_groq(
                            client, image_bytes, mime_type, model
                        )
                    break

                except Exception as exc:
                    last_error = exc
                    message = str(exc)
                    lower = message.lower()

                    # A daily quota exhaustion will not resolve by
                    # repeatedly retrying in the same run.
                    if (
                        ("429" in message or "rate" in lower or "quota" in lower)
                        and any(term in lower for term in [
                            "per day", "daily", "tokens/day",
                            "requests per day", "daily limit"
                        ])
                    ):
                        raise RuntimeError(
                            "Daily quota appears exhausted: " + message[:700]
                        )

                    if attempt == 4:
                        raise

                    wait = min(30 * (2 ** attempt), 240)
                    print(
                        f"  Request failed; retrying in {wait}s: "
                        f"{type(exc).__name__}: {message[:250]}",
                        flush=True,
                    )
                    time.sleep(wait)

            if raw is None:
                raise last_error or RuntimeError("No response received.")

            probability = parse_probability(raw)

            record.update({
                "p_fake": probability,
                "raw_response": raw,
                "status": "success",
                "error": None,
                "timestamp_utc": datetime.now(timezone.utc).isoformat(),
            })

            print(f"  p_fake = {probability}", flush=True)

        except Exception as exc:
            record.update({
                "error": f"{type(exc).__name__}: {str(exc)[:1000]}",
                "timestamp_utc": datetime.now(timezone.utc).isoformat(),
            })
            print(f"  ERROR: {record['error']}", flush=True)

        records[sha] = record

        # Save after every image so interruptions don't lose progress.
        pd.DataFrame(records.values()).to_csv(output_file, index=False)

        if record["status"] != "success":
            error_text = record.get("error", "").lower()
            if "daily quota appears exhausted" in error_text:
                print("\nStopping because the daily quota appears exhausted.")
                break

        if index < len(pending):
            time.sleep(delay)

    successful = sum(
        record.get("status") == "success"
        for record in records.values()
    )
    failed = sum(
        record.get("status") != "success"
        for record in records.values()
    )

    print("\nRun finished.")
    print("Successful predictions:", successful)
    print("Unsuccessful predictions:", failed)
    print("Saved to:", output_file)


if __name__ == "__main__":
    main()
