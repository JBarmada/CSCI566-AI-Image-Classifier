def canonical_json(value: Any) -> str:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def config_hash(config: dict[str, Any]) -> str:
    return hashlib.sha256(canonical_json(config).encode("utf-8")).hexdigest()


def request_key(row: dict[str, Any]) -> tuple[str, ...]:
    return tuple(
        str(row[field])
        for field in (
            "source_image_id",
            "submitted_image_sha256",
            "view",
            "model_id_requested",
            "prompt_sha256",
            "configuration_sha256",
        )
    )


def parse_score(raw: str) -> float:
    if not isinstance(raw, str) or not raw.strip():
        raise ValueError("empty response")
    try:
        payload = json.loads(raw)
    except json.JSONDecodeError as exc:
        raise ValueError(f"response is not a JSON object: {exc.msg}") from exc
    if not isinstance(payload, dict) or "p_fake" not in payload:
        raise ValueError("response must be a JSON object with p_fake")
    value = payload["p_fake"]
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ValueError("p_fake must be a JSON number")
    score = float(value)
    if not math.isfinite(score) or not 0 <= score <= 100:
        raise ValueError("p_fake must be finite and in [0, 100]")
    return score


def score_metrics(frame: pd.DataFrame, score_column: str = "p_fake",
                  prediction_column: str | None = None) -> dict[str, Any]:
    """Metrics for valid scores only; the caller records coverage separately."""
    data = frame.dropna(subset=["label", score_column]).copy()
    labels = data["label"].astype(int).to_numpy()
    scores = data[score_column].astype(float).to_numpy()
    predictions = (
        data[prediction_column].astype(int).to_numpy()
        if prediction_column
        else (scores >= THRESHOLD).astype(int)
    )
    real = labels == 0
    fake = labels == 1
    tp = int(((labels == 1) & (predictions == 1)).sum())
    tn = int(((labels == 0) & (predictions == 0)).sum())
    fp = int(((labels == 0) & (predictions == 1)).sum())
    fn = int(((labels == 1) & (predictions == 0)).sum())
    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else float("nan")
    specificity = tn / (tn + fp) if tn + fp else float("nan")
    f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
    auc = roc_auc_score(labels, scores) if len(np.unique(labels)) == 2 else float("nan")
    return {
        "n_valid": len(data),
        "n_unique_images": int(data["source_image_id"].nunique())
        if "source_image_id" in data else int(data["sha256"].nunique())
        if "sha256" in data else len(data),
        "n_real": int(real.sum()),
        "n_fake": int(fake.sum()),
        "accuracy": float((predictions == labels).mean()) if len(data) else float("nan"),
        "precision": precision,
        "recall": recall,
        "specificity": specificity,
        "f1": f1,
        "balanced_accuracy": (
            float((recall + specificity) / 2)
            if np.isfinite(recall) and np.isfinite(specificity) else float("nan")
        ),
        "auroc": float(auc),
        "tn": tn,
        "fp": fp,
        "fn": fn,
        "tp": tp,
        "real_false_positive_rate": fp / (fp + tn) if fp + tn else float("nan"),
        "fake_miss_rate": fn / (fn + tp) if fn + tp else float("nan"),
    }


def safe_model_slug(model_id: str) -> str:
    return re.sub(r"[^A-Za-z0-9._-]+", "-", model_id).strip("-") or "model"
